# The sub-agent's own program -- a real, separate process
# ---------------------------------------------------------------------------

_SUBAGENT_PROGRAM = """
import json, os, socket, sys

socket_path, path, content, nonce_fd = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4])
nonce = os.read(nonce_fd, 4096).decode()
os.close(nonce_fd)

sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
sock.connect(socket_path)
sock.sendall(nonce.encode())
response = sock.recv(1)
sock.close()

if response != b"1":
    print(json.dumps({"checked_in": False, "pid": os.getpid()}))
    sys.exit(1)

with open(path, "w") as f:
    f.write(content)

print(json.dumps({"checked_in": True, "pid": os.getpid(), "self_reported_uid": os.getuid()}))
"""

_NEVER_CHECKS_IN_PROGRAM = "import time\ntime.sleep(30)\n"


class Executor:
    def __init__(self, gate: Gate) -> None:
        self._gate = gate

    def execute(self, decision: Decision, intent: Intent, *, _subagent_program: str = _SUBAGENT_PROGRAM,
                _checkin_timeout: float = 5.0) -> dict:
        if decision.intent_id != intent.intent_id or decision.kind != intent.kind:
            raise GateViolation("decision does not correspond to this intent")
        if not self._gate.verify(decision):
            raise GateViolation("decision failed Gate verification -- forged, tampered, or downgraded")
        if not decision.permitted:
            raise GateViolation("decision denies this intent")

        if intent.kind == "delegate" and decision.execution_class == "uid_cgroup":
            return self._execute_delegate_uid_cgroup(
                decision, intent, subagent_program=_subagent_program, checkin_timeout=_checkin_timeout
            )
        raise GateViolation(f"no executor handler for kind={intent.kind!r} execution_class={decision.execution_class!r}")

    def _execute_delegate_uid_cgroup(self, decision: Decision, intent: Intent, *, subagent_program: str,
                                      checkin_timeout: float) -> dict:
        execution_id = decision.intent_id
        path = intent.payload["path"]
        content = intent.payload["content"]
        observations: dict = {}

        username, uid, gid = provision_ephemeral_user(execution_id)
        observations["provisioned_uid"] = uid
        cgroup_path = provision_cgroup(execution_id)
        observations["cgroup_path"] = str(cgroup_path)

        socket_path = f"/tmp/sipho-005-checkin-{execution_id}.sock"
        if os.path.exists(socket_path):
            os.unlink(socket_path)
        listener = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        listener.bind(socket_path)
        # bind() creates the socket with the broker's own (root) umask permissions -- a
        # provisioned, unprivileged uid has no write access to connect() to it otherwise. Widening
        # to 0o777 does not weaken verification: the actual security boundary below is the
        # nonce+SO_PEERCRED check, which rejects anything that doesn't match regardless of how it
        # reached accept() at all.
        os.chmod(socket_path, 0o777)
        listener.listen(1)
        listener.settimeout(checkin_timeout)

        nonce = secrets.token_hex(32)
        read_fd, write_fd = os.pipe()
        os.write(write_fd, nonce.encode())
        os.close(write_fd)

        def _drop_privileges() -> None:
            os.setgroups([])
            os.setgid(gid)
            os.setuid(uid)

        proc: subprocess.Popen | None = None
        checkin: dict = {"received": False}
        try:
            try:
                proc = subprocess.Popen(
                    [sys.executable, "-c", subagent_program, socket_path, path, content, str(read_fd)],
                    pass_fds=(read_fd,),
                    preexec_fn=_drop_privileges,
                    stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
                )
                os.close(read_fd)
                add_pid_to_cgroup(cgroup_path, proc.pid)
                observations["cgroup_members_before_checkin"] = sorted(read_cgroup_procs(cgroup_path))

                try:
                    conn, _ = listener.accept()
                except (socket.timeout, TimeoutError):
                    checkin["timed_out"] = True
                    raise CheckinError(f"sub-agent {execution_id} never checked in within {checkin_timeout}s")

                with conn:
                    presented_nonce = conn.recv(4096).decode()
                    peer_uid = _read_peer_uid(conn)
                    real_uid_from_proc = read_real_uid_from_proc(proc.pid)  # second, independent kernel source
                    checkin["received"] = True
                    checkin["presented_nonce_matches"] = hmac.compare_digest(presented_nonce, nonce)
                    checkin["peer_uid_from_so_peercred"] = peer_uid
                    checkin["peer_uid_from_proc_status"] = real_uid_from_proc
                    checkin["peer_uid_matches_provisioned"] = peer_uid == uid
                    checkin["two_kernel_sources_agree"] = peer_uid == real_uid_from_proc
                    verified = (
                        checkin["presented_nonce_matches"]
                        and checkin["peer_uid_matches_provisioned"]
                        and checkin["two_kernel_sources_agree"]
                    )
                    checkin["verified"] = verified
                    conn.sendall(b"1" if verified else b"0")

                if not verified:
                    raise CheckinError(f"sub-agent {execution_id} failed check-in verification")

                stdout, stderr = proc.communicate(timeout=10)
                observations["child_returncode"] = proc.returncode
                if proc.returncode != 0:
                    raise ProvisioningError(f"sub-agent exited nonzero after check-in: {stderr!r}")
                observations["child_self_report"] = json.loads(stdout.strip())
                observations["checkin"] = checkin

                return {
                    "effect": "delegate",
                    "execution_class": "uid_cgroup",
                    "acting_pid": proc.pid,
                    "observations": observations,
                }
            finally:
                if proc is not None and proc.poll() is None:
                    proc.kill()
                    try:
                        proc.wait(timeout=5)
                    except subprocess.TimeoutExpired:
                        pass
                for fd in (read_fd, write_fd):
                    try:
                        os.close(fd)
                    except OSError:
                        pass
                listener.close()
                if os.path.exists(socket_path):
                    os.unlink(socket_path)
        finally:
            # Release on EVERY exit path (success, check-in failure, timeout, exception) -- 004's
            # write-up named exactly this as an unfixed gap (release logic only reached on the
            # success path, leaking a real user+cgroup on a mid-execution failure). Fixed here by
            # putting release in this outer finally, wrapping the whole provision-through-dispatch
            # sequence, not just the fd/process cleanup.
            try:
                release_cgroup(cgroup_path)
                observations["cgroup_released"] = not cgroup_path.exists()
            except ProvisioningError:
                observations["cgroup_released"] = False
            release_ephemeral_user(username)
            try:
                pwd.getpwnam(username)
                observations["user_released"] = False
            except KeyError:
                observations["user_released"] = True


