"""005 -- delegation dispatched under its own provisioned uid, trusted only after a real check-in.

See `lab/005-delegation-with-uid-cgroup.md` for the hypothesis (with explicit null), method, and
analysis. This script runs the experiment and writes results under `out/005/`.

Combines 002 (delegation reduces to the same Gate/Decision/Executor primitive) with 004
(uid+cgroup as a real execution class), and adds the one mechanism neither needed on its own: a
real check-in protocol. 004's effect was a hardcoded script the Executor wrote and trusted the
instant it was spawned under the right uid -- there was nothing for the spawned process to prove,
because the Executor already knew exactly what it would do. A *delegated* unit of work is
different: the broker hands off to a separately-dispatched sub-agent and only finds out it's
legitimate by independently verifying it, the same way HISTORY.md's account of v1 already
identified this as the natural next composition needing the check-in protocol.

Check-in mechanism: a nonce (generated by the broker, handed to the child only via an inherited
pipe fd -- never argv, which is world-readable via /proc/<pid>/cmdline on real Linux, a lesson
HISTORY.md records from v1 the hard way) plus SO_PEERCRED (the kernel's own record of which real
uid actually holds the other end of a Unix socket connection, not anything the connecting process
can assert). Both must agree before the broker treats the delegated sub-agent as trustworthy enough
to let it perform its actual effect, or to trust the effect it already performed.

Built entirely fresh -- no import, copy, or "remembering" of any prior version of this mechanism
(v1's checkin.py, or the earlier lab/004 built before this repo's archive was deleted). Needs real
root on real Linux for the same reasons 004 does; refuses cleanly everywhere else.

Run (from macOS, will refuse -- confirms the refusal path)::

    cd /Users/shunhonda/dev/siphonophore
    python3 lab/005_delegation_with_uid_cgroup.py

Run for real, as root, on colima::

    colima ssh -- bash -c "cd /Users/shunhonda/dev/siphonophore && sudo python3 lab/005_delegation_with_uid_cgroup.py"
"""
