def run() -> dict:
    OUT.mkdir(parents=True, exist_ok=True)
    workdir = Path(tempfile.mkdtemp(prefix="sipho-005-"))
    os.chmod(workdir, 0o777)  # same reason as 004: the provisioned uid needs to write here
    results: dict = {"workdir": str(workdir), "broker_pid": os.getpid(), "broker_uid": os.getuid()}

    gate = Gate()
    executor = Executor(gate)

    # --- Predicate A: happy path -- mediated delegation succeeds, sub-agent checked in for real,
    # two independent kernel sources (SO_PEERCRED, /proc/<pid>/status) agree with each other and
    # with the child's own self-report, and the effect is confirmed on disk. -------------------
    a_path = workdir / "delegated_effect.txt"
    a_content = f"written by a checked-in delegate, nonce={uuid.uuid4().hex}"
    a_intent = Intent(
        kind="delegate", principal_id="principal-alice", intent_id=str(uuid.uuid4()),
        payload={"path": str(a_path), "content": a_content}, consequence="privileged",
    )
    a_decision = gate.submit(a_intent)
    assert a_decision.execution_class == "uid_cgroup"
    a_effect = executor.execute(a_decision, a_intent)
    a_obs = a_effect["observations"]
    a_checkin = a_obs["checkin"]

    results["predicate_a_happy_path"] = {
        "file_content_matches": a_path.exists() and a_path.read_text() == a_content,
        "checkin_verified": a_checkin["verified"],
        "provisioned_uid": a_obs["provisioned_uid"],
        "broker_uid": results["broker_uid"],
        "provisioned_uid_differs_from_broker": a_obs["provisioned_uid"] != results["broker_uid"],
        "so_peercred_matches_provisioned": a_checkin["peer_uid_matches_provisioned"],
        "so_peercred_matches_proc_status": a_checkin["two_kernel_sources_agree"],
        "self_report_uid_matches_kernel": (
            a_obs["child_self_report"]["self_reported_uid"] == a_checkin["peer_uid_from_so_peercred"]
        ),
        "cgroup_released": a_obs["cgroup_released"],
        "user_released": a_obs["user_released"],
    }

    # --- Predicate B: impersonation -- a connection presenting the WRONG nonce is refused, and
    # the delegation is reported as failed, not silently trusted. -------------------------------
    b_path = workdir / "impersonation_effect.txt"
    b_intent = Intent(
        kind="delegate", principal_id="principal-mallory", intent_id=str(uuid.uuid4()),
        payload={"path": str(b_path), "content": "should never appear"}, consequence="privileged",
    )
    b_decision = gate.submit(b_intent)

    _WRONG_NONCE_PROGRAM = _SUBAGENT_PROGRAM.replace(
        "nonce = os.read(nonce_fd, 4096).decode()",
        "os.read(nonce_fd, 4096)\nnonce = 'a-completely-wrong-guessed-nonce'",
    )
    b_failed = False
    b_error = None
    try:
        executor.execute(b_decision, b_intent, _subagent_program=_WRONG_NONCE_PROGRAM)
    except CheckinError as exc:
        b_failed = True
        b_error = str(exc)

    users_after_b = {pw.pw_name for pw in pwd.getpwall()}
    results["predicate_b_impersonation_refused"] = {
        "raised_checkin_error": b_failed,
        "error": b_error,
        "target_file_absent": not b_path.exists(),
        "no_leftover_sipho5_user": not any(u.startswith("sipho5-") for u in users_after_b),
    }

    # --- Predicate C: a sub-agent that never checks in at all times out, is killed, and cleanup
    # still runs (release-on-every-exit-path, the exact gap 004 named and this experiment fixes). -
    c_path = workdir / "never_checks_in_effect.txt"
    c_intent = Intent(
        kind="delegate", principal_id="principal-carol", intent_id=str(uuid.uuid4()),
        payload={"path": str(c_path), "content": "should never appear"}, consequence="privileged",
    )
    c_decision = gate.submit(c_intent)
    c_failed = False
    c_error = None
    try:
        executor.execute(c_decision, c_intent, _subagent_program=_NEVER_CHECKS_IN_PROGRAM, _checkin_timeout=1.5)
    except CheckinError as exc:
        c_failed = True
        c_error = str(exc)

    users_after_c = {pw.pw_name for pw in pwd.getpwall()}
    cgroups_after_c = set(CGROUP_ROOT.iterdir()) if CGROUP_ROOT.exists() else set()
    results["predicate_c_never_checks_in_times_out"] = {
        "raised_checkin_error": c_failed,
        "error": c_error,
        "target_file_absent": not c_path.exists(),
        "no_leftover_sipho5_user": not any(u.startswith("sipho5-") for u in users_after_c),
        "no_leftover_exec_cgroup": not any(p.name.startswith(f"exec-{c_intent.intent_id}") for p in cgroups_after_c),
    }

    # --- Predicate D: forged Decision (never through Gate.submit()) is refused before any
    # provisioning happens at all -- no user, no cgroup, no socket, no subprocess. ---------------
    d_path = workdir / "forged.txt"
    d_intent = Intent(
        kind="delegate", principal_id="principal-eve", intent_id=str(uuid.uuid4()),
        payload={"path": str(d_path), "content": "should never appear"}, consequence="privileged",
    )
    d_forged = Decision(
        intent_id=d_intent.intent_id, principal_id=d_intent.principal_id, kind=d_intent.kind,
        permitted=True, execution_class="uid_cgroup", token="beadfeed" * 8,
    )
    users_before_d = {pw.pw_name for pw in pwd.getpwall()}
    d_refused = False
    try:
        executor.execute(d_forged, d_intent)
    except GateViolation:
        d_refused = True
    users_after_d = {pw.pw_name for pw in pwd.getpwall()}

    results["predicate_d_forged_refused_no_provisioning"] = {
        "refused": d_refused,
        "target_file_absent": not d_path.exists(),
        "no_new_users_provisioned": users_after_d == users_before_d,
    }

    return results


def main() -> int:
    require_real_root_linux()
    results = run()

    out_path = OUT / "results.json"
    out_path.write_text(json.dumps(results, indent=2, default=str))
    print(f"wrote {out_path}")
    print(json.dumps(results, indent=2, default=str))

    a = results["predicate_a_happy_path"]
    b = results["predicate_b_impersonation_refused"]
    c = results["predicate_c_never_checks_in_times_out"]
    d = results["predicate_d_forged_refused_no_provisioning"]

    checks = [
        ("happy path: file content matches", a["file_content_matches"] is True),
        ("happy path: check-in verified", a["checkin_verified"] is True),
        ("happy path: provisioned uid differs from broker", a["provisioned_uid_differs_from_broker"] is True),
        ("happy path: SO_PEERCRED matches provisioned uid", a["so_peercred_matches_provisioned"] is True),
        ("happy path: SO_PEERCRED matches /proc/status", a["so_peercred_matches_proc_status"] is True),
        ("happy path: self-report matches kernel ground truth", a["self_report_uid_matches_kernel"] is True),
        ("happy path: cgroup released", a["cgroup_released"] is True),
        ("happy path: user released", a["user_released"] is True),
        ("impersonation: CheckinError raised", b["raised_checkin_error"] is True),
        ("impersonation: target file absent", b["target_file_absent"] is True),
        ("impersonation: no leftover user", b["no_leftover_sipho5_user"] is True),
        ("timeout: CheckinError raised", c["raised_checkin_error"] is True),
        ("timeout: target file absent", c["target_file_absent"] is True),
        ("timeout: no leftover user", c["no_leftover_sipho5_user"] is True),
        ("timeout: no leftover cgroup", c["no_leftover_exec_cgroup"] is True),
        ("forged: refused", d["refused"] is True),
        ("forged: target file absent", d["target_file_absent"] is True),
        ("forged: no provisioning side effects", d["no_new_users_provisioned"] is True),
    ]
    ok = True
    for name, passed in checks:
        print(f"[{'PASS' if passed else 'FAIL'}] {name}")
        ok = ok and passed

    shutil.rmtree(results["workdir"], ignore_errors=True)

    if not ok:
        print("HYPOTHESIS NOT SUPPORTED", file=sys.stderr)
        return 1
    print("HYPOTHESIS SUPPORTED")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
